/**
 * GitHub Flavored Markdown PR Review Comment Generator.
 * Formats static analysis and security findings for automated CI pull request comments.
 */

function generateMarkdownReport(result) {
  const { target = "Repository", metrics = {}, findings = [] } = result;
  const score = metrics.score ?? 100;
  const grade = metrics.grade ?? "A+";
  const status = metrics.status ?? "PRODUCTION_READY";
  const breakdown = metrics.breakdown ?? { critical: 0, high: 0, medium: 0, low: 0, total: 0 };

  let statusBadge = "🟢 **PRODUCTION READY**";
  if (status === "BLOCKED") {
    statusBadge = "🔴 **BLOCKED (Security Gates Failed)**";
  } else if (status === "REQUIRES_REVIEW") {
    statusBadge = "🟡 **REQUIRES SECURITY REVIEW**";
  }

  const lines = [
    `## 🛡️ Codexa Security & Production Readiness Audit`,
    ``,
    `> **Target:** \`${target}\` | **Gate Status:** ${statusBadge}`,
    ``,
    `| Metric | Value |`,
    `|:---|:---:|`,
    `| **Readiness Score** | **${score} / 100** (Grade: **${grade}**) |`,
    `| 🔴 **Critical Findings** | **${breakdown.critical ?? 0}** |`,
    `| 🟠 **High Findings** | **${breakdown.high ?? 0}** |`,
    `| 🟡 **Medium Findings** | **${breakdown.medium ?? 0}** |`,
    `| 🔵 **Low / Code Quality** | **${breakdown.low ?? 0}** |`,
    `| 📊 **Total Issues** | **${breakdown.total ?? findings.length}** |`,
    ``
  ];

  if (findings.length === 0) {
    lines.push(`### ✨ Clean Audit`);
    lines.push(`No vulnerabilities or high-risk code smells detected. Safe to merge! 🚀`);
    return lines.join("\n");
  }

  lines.push(`### ⚠️ Detected Findings (${Math.min(10, findings.length)} of ${findings.length} shown)`);
  lines.push(``);
  lines.push(`| Severity | Rule ID | Location | Summary |`);
  lines.push(`|:---:|:---|:---|:---|`);

  const topFindings = findings.slice(0, 10);
  for (const f of topFindings) {
    const sevIcon = f.severity === "CRITICAL" ? "🔴" : f.severity === "HIGH" ? "🟠" : f.severity === "MEDIUM" ? "🟡" : "🔵";
    lines.push(`| ${sevIcon} \`${f.severity}\` | **${f.ruleId}** | \`${f.file}:${f.line}\` | ${f.title} |`);
  }

  lines.push(``);
  lines.push(`<details>`);
  lines.push(`<summary><b>View Remediation Guidelines</b></summary>`);
  lines.push(``);
  for (const f of topFindings) {
    lines.push(`- **[${f.ruleId}]** \`${f.file}:${f.line}\`: ${f.remediation || "Review code against safe patterns."}`);
  }
  lines.push(``);
  lines.push(`</details>`);
  lines.push(``);
  lines.push(`---`);
  lines.push(`*Generated by [Codexa Security Platform](https://github.com/Codewithjainam7/Codexa)*`);

  return lines.join("\n");
}

module.exports = {
  generateMarkdownReport
};
